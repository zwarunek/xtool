            if mode == 'fast' and s == 'float':
                if n == 1:
                    mw(f'inline {ty} fract({ty} x) {{ return {c}(x); }}')
                else:
                    mw(f'inline {ty} fract({ty} x) {{ {ty} r; ' + ' '.join(f'r[{i}] = {c}(x[{i}]);' for i in range(n)) + ' return r; }')
            else:
                fl = air(f'air.floor.{suffix(s, 1)}', s, [s])
                mn = air(f'air.fmin.{suffix(s, 1)}', s, [s, s])
                one = '0x1.fffffep-1f' if s == 'float' else '(half)0x1.ffcp-1f'
                bits = 'uint' if s == 'float' else 'ushort'
                expm = '0x7f800000u' if s == 'float' else '(ushort)0x7c00'
                absm = '0x7fffffffu' if s == 'float' else '(ushort)0x7fff'
                sgn = '0x80000000u' if s == 'float' else '(ushort)0x8000'
