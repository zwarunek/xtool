mw('namespace metal {')

def fsig(fn, ty, n):
    return ', '.join(f'{ty} {"xyz"[i]}' for i in range(n))

for mode in ('fast', 'precise'):
    mw(f'namespace {mode} {{')
    for s in FLOATS:
        for n in [1] + VEC:
            ty = tname(s, n)
            sf = suffix(s, n)
            for fns, ar in ((F1, 1), (F2, 2), (F3, 3)):
                for fn in fns:
                    if fn.endswith('_'):
                        continue
                    pre = 'fast_' if (mode == 'fast' and s == 'float' and fn not in NOFAST) else ''
                    c = air(f'air.{pre}{fn}.{sf}', ty, [ty] * ar)
                    args = ', '.join('xyz'[i] for i in range(ar))
                    mw(f'inline {ty} {fn}({fsig(fn, ty, ar)}) {{ return {c}({args}); }}')
                    if n > 1 and fn in ('fmax', 'fmin', 'pow', 'powr', 'atan2', 'fmod'):
                        mw(f'inline {ty} {fn}({ty} x, {s} y) {{ return {fn}(x, {ty}(y)); }}')
