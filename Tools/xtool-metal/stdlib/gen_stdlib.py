"""Generate the xtmetal Metal standard library headers (C++ for OpenCL that calls AIR intrinsics).

Written from the Metal Shading Language specification; the AIR intrinsic names and signatures were found
by compiling probe shaders with Apple's compiler and reading the resulting AIR (see probes/).
"""
