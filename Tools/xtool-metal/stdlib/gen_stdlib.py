def tname(s, n):
    return s if n == 1 else f'{s}{n}'

def suffix(s, n):
    a = dict((x[0], x[2]) for x in SCALARS)[s]
    if s == 'bool':
        a = 'i1'
    return a if n == 1 else f'v{n}{a}'

def kind(s):
    return dict((x[0], x[3]) for x in SCALARS)[s]

decls = {}   # air name -> C declaration

_cnames = {}

def air(name, ret, args, pure=True):
    key = (name, ret, tuple(args))
    if key in _cnames:
        return _cnames[key]
    cname = '__air_' + name.replace('.', '_')
    n = sum(1 for k in _cnames if k[0] == name)
    if n:
        cname += f'_{n}'
    _cnames[key] = cname
    attr = ' __attribute__((const, nothrow))' if pure else ' __attribute__((nothrow))'
    decls[key] = f'extern "C" {ret} {cname}({", ".join(args)}) __asm("{name}"){attr};'
    return cname

